const mongoose = require('mongoose');

const quizSchema = new mongoose.Schema({
    title: { type: String, required: true },
    course: { type: mongoose.Schema.Types.ObjectId, ref: 'Course' },
    strategy: { type: String, default: 'manual' },
    subject: { type: String },    // Subject the exam covers (all exam types)
    classLevel: { type: String }, // Class level (all exam types)
    chapter: { type: String },    // Syllabus chapter
    chapters: [{ type: String }], // Multiple syllabus chapters (Optional)
    segment: { type: String, default: '', trim: true }, // Syllabus segment (if subject is ruled)
    topic: { type: String },      // Primary topic
    topics: [{ type: String }],   // All selected topics
    subTopic: { type: String, default: '' },
    subTopics: [{ type: String }],
    isModelTest: { type: Boolean, default: false },
    isMockTest: { type: Boolean, default: false },
    isBangla: { type: Boolean, default: false },
    language: { type: String, enum: ['en', 'bn'], default: 'en' },
    duration: { type: Number, default: 10 }, // Duration in minutes
    questions: [{
        questionType: { type: String, enum: ['MCQ', 'Short', 'Medium', 'Comprehension', 'Descriptive'], default: 'MCQ' },
        mcqSubtype: { type: String, enum: ['standard', 'multiple_completion', 'contextual'], default: 'standard' },
        statements: [{ type: String }],
        contextId: { type: String, default: '' },
        contextInstruction: { type: String, default: '' },
        isBangla: { type: Boolean, default: false },
        language: { type: String, enum: ['en', 'bn'], default: 'en' },
        isAutoGenerated: { type: Boolean, default: false },
        questionText: { type: String },
        questionImage: { type: String, default: '' },
        questionImagePosition: { type: String, enum: ['above', 'below', 'left', 'right'], default: 'above' },
        contextImage: { type: String, default: '' },
        explanationImage: { type: String, default: '' },
        options: [String], // Used for MCQ
        correctAnswerIndex: { type: Number }, // Used for MCQ
        correctAnswer: { type: String }, // Used for Short/Medium
        explanation: { type: String },
        answer: { type: String },
        context: { type: String },
        q1: { type: String, default: '' },
        q2: { type: String, default: '' },
        q3: { type: String, default: '' },
        q4: { type: String, default: '' },
        a1: { type: String, default: '' },
        a2: { type: String, default: '' },
        a3: { type: String, default: '' },
        a4: { type: String, default: '' },
        s1: { type: String, default: '' },
        s2: { type: String, default: '' },
        s3: { type: String, default: '' },
        s4: { type: String, default: '' },
        solution1: { type: String, default: '' },
        solution2: { type: String, default: '' },
        solution3: { type: String, default: '' },
        solution4: { type: String, default: '' },
        marks: { type: Number },
        chapter: { type: String, default: '' },
        segment: { type: String, default: '', trim: true },
        topic: { type: String, default: '' },
        subTopic: { type: String, default: '' },
        board: { type: String },
        year: { type: String }
    }],
    accessType: { type: String, enum: ['Free', 'Paid'], default: 'Free' },
    status: { type: String, enum: ['draft', 'published'], default: 'draft' },
    isDraft: { type: Boolean, default: true },
    syncGroup: { type: String },  // Links cross-class synced quizzes together
    scheduledAt: { type: Date }, // Time when the exam becomes joinable
    expiresAt: { type: Date },   // Time when the exam disappears (12h window)
    addedBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User' },
    createdAt: { type: Date, default: Date.now }
});

// High-performance indexes for live model tests, student exams, and queries
quizSchema.index({ course: 1 });
quizSchema.index({ status: 1 });
quizSchema.index({ classLevel: 1, subject: 1 });
quizSchema.index({ isMockTest: 1, status: 1 });
quizSchema.index({ isModelTest: 1, status: 1 });
quizSchema.index({ classLevel: 1, subject: 1, chapter: 1, topic: 1 });
quizSchema.index({ scheduledAt: 1, expiresAt: 1 });
quizSchema.index({ createdAt: -1 });
quizSchema.index({ syncGroup: 1 });

module.exports = mongoose.model('Quiz', quizSchema);
